test('an analyst switches sports, inspects exact forecasts and finds a team', async ({ page, request }, testInfo) => {
  const response = await request.get('http://127.0.0.1:8765/predictions')
  expect(response.ok()).toBeTruthy()
  expect((await response.json()).rows).toEqual(forecasts)
  await page.goto('/')
  await expect(page.getByText('Local workspace', { exact: true })).toBeVisible()
  await capture(page, testInfo, 'arena-live-overview.png')
  await navigate(page, 'Forecasts')
  await expectForecast(page, forecasts.find(p => p.sport === 'football')!)
  await page.getByRole('button', { name: 'VALORANT', exact: true }).click()
  await expect(page.getByRole('button', { name: 'VALORANT', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expectForecast(page, forecasts.find(p => p.sport === 'valorant')!)
  await capture(page, testInfo, 'arena-live-valorant.png')
  await navigate(page, 'Team explorer')
  await page.getByRole('textbox', { name: 'Search teams' }).fill('Neon Wolves')
  await expect(page.getByRole('heading', { name: 'Neon Wolves', exact: true })).toBeVisible()
  await expect(page.getByText('Map difference', { exact: true })).toBeVisible()
  await expect(page.getByText('Goal difference', { exact: true })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Sort teams' }).selectOption('name')
  await page.getByRole('textbox', { name: 'Search teams' }).fill('unlisted-test-team')
  await expect(page.getByText(/No teams match/)).toBeVisible()
  await noPageOverflow(page)
})

test('evidence chat returns an owned trace, inspectable sources and stored feedback', async ({ page }, testInfo) => {
  const forecast = forecasts.find(p => p.sport === 'football')!
  await page.goto('/')
  await expect(page.getByText('Local workspace', { exact: true })).toBeVisible()
  await navigate(page, 'Ask Arena')
  const question = `Show stored forecast probabilities for ${forecast.match_id}.`
  await page.getByRole('textbox', { name: 'Your question' }).fill(question)
  const chat = page.waitForResponse(r => r.url().endsWith('/api/chat') && r.request().method() === 'POST')
  await page.getByRole('main').getByRole('button', { name: 'Ask Arena', exact: true }).click()
  const result = await chat
  expect(result.status()).toBe(200)
  const answer = await result.json()
  expect(answer.mode).toBe('evidence')
  expect(answer.trace_id).toMatch(/^[a-f0-9]{32}$/)
  expect(answer.tool_results.find((e: { tool: string }) => e.tool === 'get_prediction').rows).toEqual([forecast])
  await expect(page.getByText(question, { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'predictions.json', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'predictions.json', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText(forecast.match_id)
  await page.getByRole('button', { name: 'Close source' }).click()
  await expect(dialog).not.toBeVisible()
  await page.getByText('Inspect tool evidence', { exact: false }).click()
  await expect(page.getByRole('main')).toContainText('get_prediction')
  const saved = page.waitForResponse(r => r.url().endsWith('/api/feedback') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Helpful answer', exact: true }).click()
  const feedback = await saved
  expect(feedback.status()).toBe(200)
  expect(feedback.request().postDataJSON()).toMatchObject({ trace_id: answer.trace_id, rating: 1 })
  await expect(page.getByRole('button', { name: 'Helpful answer', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Unhelpful answer', exact: true })).toBeDisabled()
  await capture(page, testInfo, 'arena-live-evidence.png')
  await page.getByRole('button', { name: 'Clear conversation', exact: true }).click()
  await expect(page.getByText(question, { exact: true })).toHaveCount(0)
  const match = knownMatches().find(row => row.match_id === 'synthetic:football:000440')!
  const expected = preMatchReference(match)
  await page.getByRole('textbox', { name: 'Your question' }).fill(`Show pre-match form and head-to-head for ${match.match_id}.`)
  const contextResponse = page.waitForResponse(r => r.url().endsWith('/api/chat') && r.request().method() === 'POST')
  await page.getByRole('main').getByRole('button', { name: 'Ask Arena', exact: true }).click()
  const context = await contextResponse
  expect(context.status()).toBe(200)
  const contextAnswer = await context.json()
  expect(contextAnswer.trace_id).not.toBe(answer.trace_id)
  const evidence = contextAnswer.tool_results.find((entry: { tool: string }) => entry.tool === 'get_match_context')
  expect(evidence.rows[0].match.match_id).toBe(match.match_id)
  expect(Date.parse(evidence.rows[0].cutoff)).toBe(Date.parse(expected.cutoff))
  expect(evidence.rows[0].form_a.played).toBe(expected.teamA.length)
  expect(evidence.rows[0].form_b.played).toBe(expected.teamB.length)
  expect(evidence.rows[0].head_to_head.total).toBe(expected.h2h.length)
  await page.getByRole('button', { name: 'gold/match_history.parquet', exact: true }).click()
  const contextSource = page.getByRole('dialog', { name: 'gold/match_history.parquet', exact: true })
  await expect(contextSource).toContainText('get_match_context')
  await expect(contextSource).toContainText('"cutoff"')
  await expect(contextSource).toContainText('observation_history')
  await expect(contextSource).toContainText(match.match_id)
  await capture(page, testInfo, 'arena-match-context-live.png', false)
  await page.getByRole('button', { name: 'Close source', exact: true }).click()
})

test('local model failure is actionable and allows an evidence retry', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('Local workspace', { exact: true })).toBeVisible()
  await navigate(page, 'Ask Arena')
  const localAI = page.getByRole('checkbox', { name: 'Local AI', exact: true })
  await localAI.check()
  const question = 'Explain the point-in-time model features.'
  await page.getByRole('textbox', { name: 'Your question' }).fill(question)
  const failed = page.waitForResponse(r => r.url().endsWith('/api/chat') && r.request().method() === 'POST')
  await page.getByRole('main').getByRole('button', { name: 'Ask Arena', exact: true }).click()
  expect((await failed).status()).toBe(503)
  await expect(page.getByRole('alert')).toContainText(/Ollama|Local model|model unavailable/i)
  await expect(page.getByText(question, { exact: true })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'Your question' })).toBeEnabled()
  await localAI.uncheck()
  await page.getByRole('textbox', { name: 'Your question' }).fill('Which data quality incidents are open?')
  const retry = page.waitForResponse(r => r.url().endsWith('/api/chat') && r.request().method() === 'POST')
  await page.getByRole('main').getByRole('button', { name: 'Ask Arena', exact: true }).click()
  expect((await retry).status()).toBe(200)
  await expect(page.getByRole('button', { name: 'incidents.json', exact: true })).toBeVisible()
})
